// Usage: node --experimental-strip-types scripts/build-map-land.mjs   (run from web/; needs ImageMagick)
// Finds the land on the Guåhan map so the puzzle home can put the island together before the sea.
// Rerun it whenever the map artwork or the village positions change; it rewrites src/puzzle/mapLand.ts,
// then check the result: tests in src/puzzle/timeline.test.ts name points that must be land or sea.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { villages } from "../src/components/village/villages.ts";

const [W, H] = [256, 320];
// The stored mask is coarser: a cell is land when most of its pixels are.
const [MW, MH] = [64, 80];
const rgb = execFileSync("magick", ["public/images/products/guahan-sunset-map/artwork-1280.webp", "-resize", `${W}x${H}!`, "-depth", "8", "rgb:-"], { maxBuffer: 1 << 24 });

// The land is a warm, light sand; the sea is blue and the sunset sky darker and redder.
function sand(i) {
  const [r, g, b] = [rgb[i * 3] / 255, rgb[i * 3 + 1] / 255, rgb[i * 3 + 2] / 255];
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const l = (max + min) / 2;
  const s = max === min ? 0 : l > 0.5 ? (max - min) / (2 - max - min) : (max - min) / (max + min);
  let h = 0;
  if (max !== min) h = max === r ? ((g - b) / (max - min)) % 6 : max === g ? (b - r) / (max - min) + 2 : (r - g) / (max - min) + 4;
  h = (h * 60 + 360) % 360;
  return h >= 18 && h <= 48 && l >= 0.6 && l <= 0.86 && s >= 0.35;
}
const spread = (mask, grow, r) => mask.map((_, i) => {
  const [x, y] = [i % W, Math.floor(i / W)];
  for (let yy = Math.max(0, y - r); yy <= Math.min(H - 1, y + r); yy++)
    for (let xx = Math.max(0, x - r); xx <= Math.min(W - 1, x + r); xx++) if (mask[yy * W + xx] === grow) return grow;
  return !grow;
});
function fill(passable, seeds) {
  const out = new Array(W * H).fill(false);
  const queue = seeds.filter((i) => passable[i]);
  queue.forEach((i) => (out[i] = true));
  while (queue.length) {
    const i = queue.pop();
    const [x, y] = [i % W, Math.floor(i / W)];
    for (const [nx, ny] of [[x + 1, y], [x - 1, y], [x, y + 1], [x, y - 1]]) {
      const n = ny * W + nx;
      if (nx >= 0 && nx < W && ny >= 0 && ny < H && !out[n] && passable[n]) {
        out[n] = true;
        queue.push(n);
      }
    }
  }
  return out;
}

// Close small gaps (icons, labels), then keep only the sand that joins a village.
const closed = spread(spread(Array.from({ length: W * H }, (_, i) => sand(i)), true, 2), false, 2);
const seeds = villages.map((v) => {
  const [x, y] = [Math.floor(v.x * W), Math.floor(v.y * H)];
  let best = -1;
  for (let r = 0; r <= 8 && best < 0; r++)
    for (let yy = y - r; yy <= y + r && best < 0; yy++)
      for (let xx = x - r; xx <= x + r && best < 0; xx++) if (xx >= 0 && xx < W && yy >= 0 && yy < H && closed[yy * W + xx]) best = yy * W + xx;
  return best;
});
const touching = fill(closed, seeds.filter((i) => i >= 0));
// Whatever the island encloses (village tints, icons) is land too: only what reaches the edge is not.
const edge = Array.from({ length: W * H }, (_, i) => i % W === 0 || i % W === W - 1 || i < W || i >= W * (H - 1)).flatMap((on, i) => (on ? [i] : []));
const enclosed = (mask) => fill(mask.map((on) => !on), edge).map((out) => !out);
// Sunset reflections on the water are the same sand color and reach the coast by thin strands. An
// opening (erode, then grow back) cuts strands narrower than 11px, and only what still
// joins a village stays.
const OPEN = 5;
const opened = spread(spread(enclosed(touching), false, OPEN), true, OPEN);
const land = enclosed(fill(opened, seeds.filter((i) => i >= 0 && opened[i])));

// Coarse cells, stored as runs of land per row ("start-end", end exclusive), so the file stays readable.
const rows = [];
for (let my = 0; my < MH; my++) {
  const runs = [];
  let start = -1;
  for (let mx = 0; mx <= MW; mx++) {
    let on = false;
    if (mx < MW) {
      let count = 0;
      for (let y = my * (H / MH); y < (my + 1) * (H / MH); y++) for (let x = mx * (W / MW); x < (mx + 1) * (W / MW); x++) count += land[y * W + x] ? 1 : 0;
      on = count * 2 >= (W / MW) * (H / MH);
    }
    if (on && start < 0) start = mx;
    if (!on && start >= 0) {
      runs.push(`${start}-${mx}`);
      start = -1;
    }
  }
  rows.push(runs.join(","));
}
writeFileSync("src/puzzle/mapLand.ts", `// Generated by scripts/build-map-land.mjs from the Guåhan map. Do not edit by hand.
// The land on the map, as ${MW} × ${MH} cells: each row lists its runs of land ("start-end", end exclusive).
export const MAP_LAND = { cols: ${MW}, rows: ${MH}, runs: ${JSON.stringify(rows, null, 2).replace(/\n/g, "\n  ")} };
`);
console.log(`Land: ${Math.round((land.filter(Boolean).length / land.length) * 100)}% of the map`);
